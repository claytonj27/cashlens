@lru_cache(maxsize=1)
def metadata() -> dict[str, dict[str, Any]]:
    if not METADATA_PATH.exists():
        return {}
    return json.loads(METADATA_PATH.read_text(encoding="utf-8")).get("items", {})


def meta_for(question_key: str) -> dict[str, Any]:
    return metadata().get(question_key, {})


def group_of(section_slug: str) -> Group:
    parts = section_slug.split("-")
    return GROUP_BY_SLUG_PART.get(parts[1], "core") if len(parts) > 1 else "core"


def level_of(section_slug: str) -> Level:
    """core | recommended | deep_dive, also for a calibration or scenario section by its tail."""
    parts = section_slug.split("-")
    if len(parts) > 1 and parts[1] in LEVEL_BY_SLUG_PART:
        return LEVEL_BY_SLUG_PART[parts[1]]
    if len(parts) > 2 and parts[2] in LEVEL_BY_SLUG_PART:
        return LEVEL_BY_SLUG_PART[parts[2]]
    return "deep_dive"


def owner_of(section_slug: str) -> str:
    return section_slug.split("-")[0]


def _segment(question_key: str) -> str:
    parts = question_key.split(".")
    return ".".join(parts[:2]) if len(parts) > 1 else parts[0]


def topic_of(question_key: str, section_slug: str) -> str:
    group = group_of(section_slug)
    if group == "calibration":
        return "Calibration"
    if group == "scenarios":
        return "Scenarios"
    if question_key.startswith("en."):
        return "Engineering"
    found = TOPIC_BY_SEGMENT.get(_segment(question_key))
    if found:
        return found
    theme = section_slug.split("-")[-1]
    return {"underwriting": "Underwriting", "operations": "Operations", "organisation": "Role"}.get(
        theme, "Business"
    )


def is_business_fact(question_key: str) -> bool:
    return bool(FACT_USES & set(meta_for(question_key).get("system_use", [])))


def business_group_of(question_key: str, section_slug: str) -> str:
    found = BUSINESS_GROUP_BY_SEGMENT.get(_segment(question_key))
    if found:
        return found
    return BUSINESS_GROUP_BY_THEME.get(section_slug.split("-")[-1], "Company scale")


def is_underwriting(question_key: str, section_slug: str) -> bool:
    if _segment(question_key) in UNDERWRITING_KEYS:
        return True
    uses = set(meta_for(question_key).get("system_use", []))
    return bool(
        uses & {"UNDERWRITING_POLICY", "THRESHOLD", "RISK_SIGNAL", "OUTCOME_LABEL"}
    ) and not question_key.startswith("en.")


def underwriting_group_of(question_key: str) -> str:
    """The first group whose keyword starts a token of the key's tail. Specific groups (payroll,
    taxes, MCA) are tried before generic ones (hard stops, eligibility), and matching is on
    tokens so that "coverage" is never read as "age"."""
    tokens = [t for t in re.split(r"[-_.]", question_key.split(".", 2)[-1].lower()) if t]
    # The leading token names the subject ("payroll-coverage" is about payroll), so tokens
    # are tried left to right, and for each token the specific groups before the generic.
    for token in tokens:
        for name, words in UNDERWRITING_GROUP_ORDER:
            if any(token.startswith(w) for w in words):
                return name
    return "Other underwriting"


def engineer_category_of(question_key: str, section_slug: str) -> str:
    if group_of(section_slug) == "scenarios" or question_key.startswith("ds-"):
        return "Technical scenarios"
    parts = question_key.split(".")
    if len(parts) > 1:
        return ENGINEER_CATEGORY_BY_SEGMENT.get(parts[1], "Architecture")
    return "Architecture"


def engineering_buckets_of(question_key: str) -> list[str]:
    meta = meta_for(question_key)
    uses = set(meta.get("system_use", []))
    out: list[str] = []
    for bucket, _rule, keys, fragments in ENGINEERING_BUCKETS:
        by_key = question_key in keys or any(f in question_key for f in fragments)
        by_use = (bucket == "What is painful" and "RISK_SIGNAL" in uses) or (
            bucket == "What is missing" and "PRODUCT_REQUIREMENT" in uses
        )
        # "What exists today" is the fallback for a FACT question filed nowhere else.
        fallback = (
            bucket == "What exists today" and not out and meta.get("semantic_class") == "FACT"
        )
        if by_key or by_use or fallback:
            out.append(bucket)
    return out
